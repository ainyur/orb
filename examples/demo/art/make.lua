local function font_file()
    local spr = Sprite(128, 48, ColorMode.INDEXED)
    local pal = Palette(8)

    pal:setColor(0, NONE)
    pal:setColor(1, BG)
    pal:setColor(2, RED)
    pal:setColor(3, WHITE)
    pal:setColor(4, DARK_RED)
    pal:setColor(5, GRAY)
    pal:setColor(6, DIM)
    pal:setColor(7, SHADOW)
    spr:setPalette(pal)
    spr.gridBounds = Rectangle(0, 0, 8, 8)

    local img = spr.cels[1].image
    img:clear(0)

    for cell, rows in ipairs(GLYPHS) do
        local ox, oy = ((cell - 1) % 16) * 8, ((cell - 1) // 16) * 8

        for y, row in ipairs(rows) do
            for x = 1, 5 do
                if row:sub(x, x) == "#" then img:putPixel(ox + x - 1, oy + y - 1, 3) end
            end
        end
    end

    spr:saveAs("examples/demo/fonts/body.aseprite")
    spr:close()
end

